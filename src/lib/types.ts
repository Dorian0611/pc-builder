// Alkatrész-adatmodell. A mezők neve angol (OpenDB-hez és kódhoz illeszkedik),
// a felületen megjelenő szövegek magyarok.
//
// Ami az OpenDB-ben hiányozhat, az opcionális: a kompatibilitás-ellenőrzés ilyenkor
// "nem ellenőrizhető" eredményt ad, sosem zöldet.

export type Category =
  | 'cpu'
  | 'motherboard'
  | 'memory'
  | 'gpu'
  | 'storage'
  | 'psu'
  | 'case'
  | 'cooler'

export type MemoryType = 'DDR4' | 'DDR5'
export type BoardFormFactor = 'E-ATX' | 'ATX' | 'mATX' | 'ITX'
export type PsuFormFactor = 'ATX' | 'SFX' | 'SFX-L'
export type StorageInterface = 'M.2 NVMe' | 'M.2 SATA' | 'SATA' | 'PCIe'

/** GPU tápcsatlakozók / táp kimenetek darabszáma */
export interface PowerConnectors {
  '12V-2x6'?: number
  '8pin'?: number
}

/** Generated by scripts/prices/update-prices.mjs into public/data/prices.json */
export interface PriceBlock {
  medianHuf: number
  minHuf: number
  /** number of distinct shops */
  offerCount: number
  /** YYYY-MM-DD */
  updatedAt: string
  sources: string[]
  links?: { source: string; url: string }[]
  /** median moved suspiciously since the previous run */
  flag?: 'jump'
}

/** Price guessed from comparable priced parts (src/lib/estimates.ts) – never a shop price. */
export interface PriceEstimate {
  /** 'foreign': this part's own prices in foreign shops, converted and calibrated;
   *  'similar': Hungarian prices of comparable parts */
  basis: 'foreign' | 'similar'
  medianHuf: number
  /** range: 25th–75th percentile (similar) or cheapest–median foreign shop (foreign) */
  lowHuf: number
  highHuf: number
  /** number of comparable parts (similar) or foreign shops (foreign) */
  count: number
}

/** public/data/foreign-prices.json, written by scripts/prices/update-prices.mjs */
export interface ForeignPrices {
  updatedAt: string
  rateDate?: string
  /** Hungarian/foreign price ratio per category ("*" = all categories) */
  factors: Record<string, number>
  items: Record<string, { medianHuf: number; minHuf: number; offerCount: number; sources: string[] }>
}

interface BasePart {
  /** OpenDB azonosító (UUID) */
  id: string
  category: Category
  brand: string
  name: string
  partNumber?: string
  releaseYear?: number
  price?: PriceBlock
  estimate?: PriceEstimate
}

export interface Cpu extends BasePart {
  category: 'cpu'
  socket: string
  cores?: number
  threads?: number
  /** névleges TDP / PBP */
  tdpW?: number
  /** tartós csúcsfogyasztás (PPT / MTP), ha ismert */
  peakW?: number
  integratedGraphics?: boolean
  memoryTypes?: MemoryType[]
  microarchitecture?: string
  /** Ezeken a lapkakészleteken a CPU-hoz BIOS-frissítés kellhet */
  biosUpdateChipsets?: string[]
  /** relatív játékteljesítmény (Ryzen 5 7600 = 100) */
  perfScore?: number
}

export interface Motherboard extends BasePart {
  category: 'motherboard'
  socket: string
  chipset?: string
  formFactor: BoardFormFactor
  memoryType: MemoryType
  memorySlots?: number
  maxMemoryGb?: number
  m2Slots?: number
  sataPorts?: number
}

export interface Memory extends BasePart {
  category: 'memory'
  memoryType: MemoryType
  modules: number
  moduleSizeGb: number
  speedMts?: number
  casLatency?: number
}

export interface Gpu extends BasePart {
  category: 'gpu'
  chip?: string
  vramGb?: number
  lengthMm?: number
  tdpW?: number
  powerConnectors?: PowerConnectors
  /** relatív játékteljesítmény (RTX 4060 = 100) */
  perfScore?: number
}

export interface Storage extends BasePart {
  category: 'storage'
  interface: StorageInterface
  capacityGb: number
  kind: 'SSD' | 'HDD'
  formFactor?: string
}

export interface Psu extends BasePart {
  category: 'psu'
  wattage: number
  formFactor: PsuFormFactor
  connectors?: PowerConnectors
  efficiency?: string
  modular?: string
  lengthMm?: number
}

export interface Case extends BasePart {
  category: 'case'
  caseType?: string
  supportedBoards: BoardFormFactor[]
  maxGpuLengthMm?: number
  maxCoolerHeightMm?: number
  maxPsuLengthMm?: number
  /** támogatott radiátorméretek (mm) – az OpenDB-ben nincs ilyen adat */
  radiatorSizesMm?: number[]
  psuFormFactors?: PsuFormFactor[]
  /** a tápméretet az alaplapméretből feltételeztük, nem az adatbázisból jön */
  psuFormFactorsInferred?: boolean
}

export interface Cooler extends BasePart {
  category: 'cooler'
  type: 'air' | 'aio'
  sockets: string[]
  heightMm?: number
  radiatorMm?: number
  fanSizeMm?: number
}

export type Part = Cpu | Motherboard | Memory | Gpu | Storage | Psu | Case | Cooler

export interface PartByCategory {
  cpu: Cpu
  motherboard: Motherboard
  memory: Memory
  gpu: Gpu
  storage: Storage
  psu: Psu
  case: Case
  cooler: Cooler
}

export type CatalogData = { [C in Category]: PartByCategory[C][] }

export interface CatalogMeta {
  source: string
  sourceUrl: string
  license: string
  licenseUrl: string
  commit: string
  importedAt: string
  counts: Partial<Record<Category, number>>
}

/** Egy összeállítás: kategóriánként a kiválasztott alkatrészek azonosítói. */
export type BuildSelection = Partial<Record<Category, string[]>>

/** Feloldott összeállítás: azonosítók helyett alkatrészek. */
export interface ResolvedBuild {
  cpu?: Cpu
  motherboard?: Motherboard
  memory: Memory[]
  gpu?: Gpu
  storage: Storage[]
  psu?: Psu
  case?: Case
  cooler?: Cooler
}

export type CheckLevel = 'error' | 'warning' | 'unknown' | 'ok'

export interface CheckResult {
  rule: string
  level: CheckLevel
  message: string
  /** az érintett alkatrészek azonosítói */
  partIds: string[]
}
